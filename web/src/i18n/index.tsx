export type Language = 'de' | 'en';

const DICTS: Record<Language, Record<string, string>> = { de, en };

export type Translate = (key: I18nKey | string, vars?: Record<string, string | number>) => string;

interface I18nValue {
  lang: Language;
  setLang(lang: Language): void;
  t: Translate;
}

const I18nContext = createContext<I18nValue | null>(null);

function detect(): Language {
  const stored = localStorage.getItem('cb_lang');
  if (stored === 'de' || stored === 'en') return stored;
  return navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }): JSX.Element {
  const [lang, setLangState] = useState<Language>(() => {
    try {
      return detect();
    } catch {
      return 'de';
    }
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem('cb_lang', lang);
    } catch {
      /* privates Fenster */
    }
  }, [lang]);

  const t = useCallback<Translate>(
    (key, vars) => {
      const dict = DICTS[lang];
      let out = dict[key] ?? DICTS.de[key] ?? String(key);
      if (vars) {
        for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
      }
      return out;
    },
    [lang],
  );

  const value = useMemo<I18nValue>(() => ({ lang, setLang: setLangState, t }), [lang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('I18nProvider fehlt');
  return ctx;
}
